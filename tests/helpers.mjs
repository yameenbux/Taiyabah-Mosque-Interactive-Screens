import { fileURLToPath } from "node:url";
export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUTS = ["timetable.html", "timetablevertical.html", "foyer.html", "foyervertical.html"];
