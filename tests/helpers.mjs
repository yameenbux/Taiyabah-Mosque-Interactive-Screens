import fs from "node:fs";
export function loadDays() {
  const days = {};
  for (const f of fs.readdirSync(path.join(ROOT, "data")).filter((f) => /^timetable-\d{4}\.json$/.test(f)).sort())
    Object.assign(days, JSON.parse(fs.readFileSync(path.join(ROOT, "data", f), "utf8")).days);
  return days;
}

