/* Serve the repo over HTTP, as GitHub Pages does: the foyer's fetch of
   foyer-content.json and the guarded reload both need a real origin. */
export async function serve() {
  const port = await new Promise((res) => { const s = net.createServer(); s.listen(0, () => { const p = s.address().port; s.close(() => res(p)); }); });
  const proc = spawn("python3", ["-m", "http.server", String(port), "--bind", "127.0.0.1"], { cwd: ROOT, stdio: "ignore" });
  for (let i = 0; i < 50; i++) {
    try { await fetch(`http://127.0.0.1:${port}/`); break; } catch { await new Promise((r) => setTimeout(r, 100)); }
  }
  return { base: `http://127.0.0.1:${port}/`, stop: () => proc.kill() };
}

/* Open a built page at a fixed local time. */
export async function openAt(browser, base, file, when, { width = 1920, height = 1080, route } = {}) {
  const ctx = await browser.newContext({ viewport: { width, height }, timezoneId: "Europe/London" });
  const page = await ctx.newPage();
  const requests = [];
  page.on("request", (r) => requests.push(r.url()));
  if (route) await route(page);
  await page.clock.install({ time: new Date(when) });
  await page.goto(base + file);
  await page.waitForFunction(() => document.fonts.status === "loaded");
  await page.waitForTimeout(150);
  return { page, ctx, requests };
}

/* Every visible element of #content inside the viewport, as offenders. */
export async function overflowing(page) {
  return page.evaluate(() => {
    const W = innerWidth, H = innerHeight, bad = [];
    for (const el of document.querySelectorAll("#content *")) {
      const r = el.getBoundingClientRect(), cs = getComputedStyle(el);
      if (!r.width || !r.height || cs.visibility === "hidden" || el.closest("[hidden]") || el.closest("[data-deco]")) continue;
      if (r.left < -1 || r.top < -1 || r.right > W + 1 || r.bottom > H + 1)
        bad.push(`${el.tagName.toLowerCase()}.${el.className && el.className.baseVal === undefined ? el.className : ""} ${Math.round(r.left)},${Math.round(r.top)},${Math.round(r.right)},${Math.round(r.bottom)}`);
    }
    return bad;
  });
}
