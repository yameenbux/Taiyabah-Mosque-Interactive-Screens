import path from "node:path";
import { fileURLToPath } from "node:url";
export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUTS = ["timetable.html", "timetablevertical.html", "foyer.html", "foyervertical.html"];
export const MARKER = "<!-- GENERATED by build.py from src/ — do not edit by hand -->";
import fs from "node:fs";
export function loadDays() {
  const days = {};
  for (const f of fs.readdirSync(path.join(ROOT, "data")).filter((f) => /^timetable-\d{4}\.json$/.test(f)).sort())
    Object.assign(days, JSON.parse(fs.readFileSync(path.join(ROOT, "data", f), "utf8")).days);
  return days;
}

