#!/usr/bin/env python3
"""Taiyabah Masjid TV screens: build the four pages the TVs open.

    python3 build.py              build timetable(.vertical).html and foyer(.vertical).html
    python3 build.py --check-only only validate the timetable data

Everything a TV needs (fonts, logo, badges, code, every year of prayer times
and a fallback copy of foyer-content.json) is put inside each page, so once a
page has loaded it needs no network to show the right times.

The source is in src/. The four .html files at the top of the repo are
OUTPUT: edit src/ and rebuild, never the outputs. They say so on line 1.

Each new year: copy the app repo's data/timetable-YYYY.json into data/, run
this, run `npm test`, commit. This refuses to build from a timetable file
with a missing or out-of-order time, rather than put a wrong time on a TV.

Python 3 standard library only, so a volunteer can run it anywhere.
"""
import argparse
import base64
import datetime
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "src")
MARKER = "<!-- GENERATED by build.py from src/ — do not edit by hand -->"
BEGINS = ["fajr", "sunrise", "zuhr", "asr", "maghrib", "isha"]
JAMAAT = ["fajr", "zuhr", "asr", "maghrib", "isha"]
HHMM = re.compile(r"^([01]\d|2[0-3]):[0-5]\d$")
# The Hijri month names exactly as the app's parser writes them. The foyer's
# Ramadan and Eid greetings match on these, so another spelling would turn
# them off silently.
HIJRI_MONTHS = {"Muharram", "Safar", "Rabi al-Awwal", "Rabi al-Thani", "Jumada al-Awwal",
                "Jumada al-Thani", "Rajab", "Sha'ban", "Ramadan", "Shawwal", "Dhul Qa'dah", "Dhul Hijjah"}
# Each jamaat must come before the next prayer begins.
JAMAAT_BEFORE = {"fajr": "sunrise", "zuhr": "asr", "asr": "maghrib", "maghrib": "isha"}

SCREENS = [
    # output file, screen folder, body class
    ("timetable.html", "timetable", "landscape"),
    ("timetablevertical.html", "timetable", "portrait"),
    ("foyer.html", "foyer", "landscape"),
    ("foyervertical.html", "foyer", "portrait"),
]


def fail(msg):
    sys.stderr.write("build.py: " + msg + "\n")
    sys.exit(1)


def read(*parts, mode="r"):
    with open(os.path.join(*parts), mode, **({} if "b" in mode else {"encoding": "utf-8"})) as f:
        return f.read()


def check_day(key, rec):
    """Every problem with one day, as a list of strings. Empty means fine."""
    errs = []
    if not isinstance(rec, dict):
        return [f"{key}: not an object"]
    try:
        datetime.date.fromisoformat(key)
    except ValueError:
        return [f"{key}: not a date"]
    b, j = rec.get("begins", {}), rec.get("jamaat", {})
    for k in BEGINS:
        if not HHMM.match(str(b.get(k, ""))):
            errs.append(f"{key}: begins.{k} missing or not HH:MM")
    for k in JAMAAT:
        if not HHMM.match(str(j.get(k, ""))):
            errs.append(f"{key}: jamaat.{k} missing or not HH:MM")
    if not errs:
        order = [b[k] for k in BEGINS]
        if order != sorted(order) or len(set(order)) != len(order):
            errs.append(f"{key}: begin times out of order {order}")
        for k in JAMAAT:
            if j[k] < b[k]:
                errs.append(f"{key}: jamaat.{k} {j[k]} is before it begins {b[k]}")
        for k, nxt in JAMAAT_BEFORE.items():
            if j[k] >= b[nxt]:
                errs.append(f"{key}: jamaat.{k} {j[k]} is not before {nxt} begins {b[nxt]}")
        jo = [j[k] for k in JAMAAT]
        if jo != sorted(jo):
            errs.append(f"{key}: jamaat times out of order {jo}")
    if datetime.date.fromisoformat(key).weekday() == 4:
        jm = rec.get("jummah") or {}
        ok = True
        for k in ("first", "second"):
            if not HHMM.match(str(jm.get(k, ""))):
                errs.append(f"{key}: Friday without jummah.{k}")
                ok = False
        # A printed "1:00" typed as "01:00" lands here: it would put Jumu'ah
        # at one in the morning.
        if ok and not errs:
            if not (b["zuhr"] <= jm["first"] < jm["second"] < b["asr"]):
                errs.append(f"{key}: jummah {jm['first']}/{jm['second']} must fall between Zuhr begins {b['zuhr']} and Asr begins {b['asr']}, 1st before 2nd")
    m = re.match(r"^\d+ (.+) \d+ AH$", str(rec.get("hijri", "")))
    if not m:
        errs.append(f"{key}: hijri missing or malformed")
    elif m.group(1) not in HIJRI_MONTHS:
        errs.append(f"{key}: hijri month '{m.group(1)}' is not one of {sorted(HIJRI_MONTHS)}")
    return errs


def load_days(data_dir):
    """Every data/timetable-*.json merged into one {date: day} map."""
    files = sorted(glob.glob(os.path.join(data_dir, "timetable-*.json")))
    if not files:
        fail(f"no timetable-*.json in {data_dir}")
    days, errs = {}, []
    for path in files:
        try:
            doc = json.loads(read(path))
        except ValueError as e:
            fail(f"{os.path.basename(path)} is not valid JSON: {e}")
        for key, rec in doc.get("days", {}).items():
            if key in days:
                errs.append(f"{key}: appears in more than one file")
            errs += check_day(key, rec)
            days[key] = {k: rec[k] for k in ("hijri", "begins", "jamaat", "jummah") if k in rec}
    if errs:
        fail("timetable data refused:\n  " + "\n  ".join(errs[:30]))
    return dict(sorted(days.items()))


def data_uri(path, mime):
    return f"data:{mime};base64," + base64.b64encode(read(path, mode="rb")).decode()


def inline_fonts(css):
    return re.sub(r"url\((fonts/[^)]+\.woff2)\)",
                  lambda m: "url(" + data_uri(os.path.join(SRC, "shared", m.group(1)), "font/woff2") + ")", css)


def script_safe(text):
    """JSON or JS that cannot close the <script> it sits in."""
    return text.replace("</", "<\\/")


def build_page(screen, body_class, days, content):
    shared = os.path.join(SRC, "shared")
    css = "\n".join([
        read(shared, "tokens.css"),
        inline_fonts(read(shared, "fonts.css")),
        read(shared, "frame.css"),
        read(SRC, screen, "screen.css"),
    ])
    js_files = [os.path.join(shared, "times.js"), os.path.join(shared, "frame.js")]
    if screen == "foyer":
        js_files.insert(0, os.path.join(shared, "qrcode.js"))
    js_files.append(os.path.join(SRC, screen, "screen.js"))
    js = "\n;\n".join(read(p) for p in js_files)
    page = read(SRC, screen, "page.html")
    fills = {
        "{{CSS}}": css,
        "{{DATA}}": "window.TT_DATA = " + script_safe(json.dumps(days, separators=(",", ":"), ensure_ascii=False)) + ";",
        "{{CONTENT}}": "window.TT_CONTENT = " + script_safe(json.dumps(content, ensure_ascii=False)) + ";",
        "{{JS}}": script_safe(js),
        "{{LOGO}}": read(shared, "logo.svg").replace("<svg ", '<svg class="logo" aria-hidden="true" ', 1),
        "{{BADGE_APPLE}}": data_uri(os.path.join(shared, "badges", "app-store.svg"), "image/svg+xml"),
        "{{BADGE_GOOGLE}}": data_uri(os.path.join(shared, "badges", "google-play.png"), "image/png"),
        "{{BODYCLASS}}": body_class,
    }
    for k, v in fills.items():
        page = page.replace(k, v)
    left = re.findall(r"\{\{[A-Z_]+\}\}", page)
    if left:
        fail(f"{screen}/page.html: unfilled placeholders {sorted(set(left))}")
    return MARKER + "\n" + page


# The foyer's donate QR must open a Stripe checkout that takes money. It once
# pointed at a page on the old website for weeks without anyone noticing.
DONATE_LINK = re.compile(r"^https://(buy|donate)\.stripe\.com/[A-Za-z0-9]+$")


def check_donate_link(content):
    try:
        url = content["newBuild"]["give"]["otherAmountUrl"]
    except (KeyError, TypeError):
        fail("foyer-content.json has no newBuild.give.otherAmountUrl for the donate QR")
    if not isinstance(url, str) or not DONATE_LINK.match(url):
        fail(f"the donate QR link must be a Stripe checkout link (https://buy.stripe.com/...), not {url!r}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=os.path.join(ROOT, "data"))
    ap.add_argument("--check-only", action="store_true")
    ap.add_argument("--out", default=ROOT, help="where to write the pages (tests build elsewhere)")
    args = ap.parse_args()
    days = load_days(args.data)
    try:
        content = json.loads(read(ROOT, "foyer-content.json"))
    except ValueError as e:
        fail(f"foyer-content.json is not valid JSON: {e}")
    check_donate_link(content)
    if args.check_only:
        print(f"data ok: {len(days)} days, {next(iter(days))} to {next(reversed(days))}")
        return
    for out, screen, cls in SCREENS:
        html = build_page(screen, cls, days, content)
        with open(os.path.join(args.out, out), "w", encoding="utf-8") as f:
            f.write(html)
        print(f"{out:26} {len(html.encode()) / 1024:7.0f} KB")
    print(f"{len(days)} days of prayer times, {next(iter(days))} to {next(reversed(days))}")


if __name__ == "__main__":
    main()
