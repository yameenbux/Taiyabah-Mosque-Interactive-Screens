/* Taiyabah Masjid screens: the frame every screen shares.
 *
 * Clock, dates, the next-jamāʿah / Jumuʿah bar, fitting the fixed-size
 * layout to whatever the TV reports, and the reliability net for a browser
 * tab left running for months. Uses TT_TIMES (times.js) and TT_DATA (put in
 * the page by build.py).
 */
"use strict";
var T = window.TT_TIMES, DAYS = window.TT_DATA;
var MARK = "GENERATED by build.py";

function esc(s) {
  return String(s).replace(/[&<>"]/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]; });
}

/* A name for a serif heading. Fraunces draws the ʿ (ayn) too wide, so it is
 * set in Hanken Grotesk, which draws it properly. */
function nameHTML(s) { return esc(s).replace(/ʿ/g, '<span class="ayn">ʿ</span>'); }

/* "15:00" -> '3:00<span class="ampm">pm</span>' */
function fmtTime(hhmm) {
  var x = T.hm12(hhmm);
  return '<span class="tn">' + x.t + '</span>\u2009<span class="ampm">' + x.ap + "</span>";
}
function hhmmOf(d) { return T.pad(d.getHours()) + ":" + T.pad(d.getMinutes()); }

function setHTML(id, html) {
  var el = document.getElementById(id);
  if (el && el.__html !== html) { el.innerHTML = html; el.__html = html; }
}

/* Header and bar. `opts.short` drops the Jumuʿah date (the foyer's narrower bar). */
function renderFrame(now, opts) {
  opts = opts || {};
  setHTML("clock", fmtTime(hhmmOf(now)));
  setHTML("greg", esc(now.toLocaleDateString("en-GB", { weekday: "long", day: "numeric", month: "long", year: "numeric" })));
  var rec = DAYS[T.dayKey(now)];
  setHTML("hijri", rec ? esc(rec.hijri) : "");

  var n = T.nextJamaah(DAYS, now);
  setHTML("next", n
    ? '<span class="eyebrow">Next jamāʿah</span><b>' + nameHTML(n.en) + " · " + fmtTime(hhmmOf(n.at)) + '</b><span class="in">' + T.countdown(n.at - now) + "</span>"
    : "");
  var j = T.nextJumuah(DAYS, now);
  var day = j && !opts.short ? '<span class="mut">' + esc(j.date.toLocaleDateString("en-GB", { weekday: "long", day: "numeric", month: "long" })) + "</span>" : "";
  setHTML("jum", j
    ? '<span class="eyebrow">Jumuʿah</span>' + day + '<span class="lab">1st</span><b class="tn">' + T.hm12(j.first).t + '</b><span class="lab">2nd</span><b>' + fmtTime(j.second) + "</b>"
    : "");
  return rec;
}

/* Scale the fixed-size layout to fill the TV, up or down, keeping its
 * proportions. A 4K TV whose browser reports 3840x2160 is filled edge to edge
 * rather than showing a half-size screen in the middle. */
function fitToViewport() {
  var c = document.getElementById("content");
  if (!c) return;
  var s = Math.min(innerWidth / c.offsetWidth, innerHeight / c.offsetHeight);
  c.style.transform = Math.abs(s - 1) > 0.001 ? "scale(" + s + ")" : "none";
}

/* Reload, but only if the network can serve this page again. Wi-Fi down at
 * 2am must leave the timetable on screen, not the browser's error page. */
var retryTimer = null;
function guardedReload() {
  clearTimeout(retryTimer);
  fetch(location.href, { cache: "no-store" })
    .then(function (r) { return r.ok ? r.text() : ""; })
    .then(function (body) {
      if (body.indexOf(MARK) !== -1) location.reload();
      else retryTimer = setTimeout(guardedReload, 15 * 60 * 1000);
    })
    .catch(function () { retryTimer = setTimeout(guardedReload, 15 * 60 * 1000); });
}
window.guardedReload = guardedReload;

function msUntil(hh, mm) {
  var now = new Date(), t = new Date(now);
  t.setHours(hh, mm, 0, 0);
  if (t <= now) t.setDate(t.getDate() + 1);
  return t - now;
}

/* tick(now) is called every second. A tick arriving 15 s late means the TV
 * suspended the tab: reload for a clean state. Daily reload at 02:00, after
 * the latest Isha jamāʿah and before the earliest Fajr. */
function startReliability(tick) {
  var last = Date.now();
  function beat() {
    var t = Date.now();
    if (t - last > 15000) { last = t; guardedReload(); return; }
    last = t;
    tick(new Date());
  }
  beat();
  setInterval(beat, 1000);
  setTimeout(function daily() { guardedReload(); setTimeout(daily, msUntil(2, 0)); }, msUntil(2, 0));
  document.addEventListener("visibilitychange", function () {
    if (document.visibilityState === "visible" && Date.now() - last > 15000) guardedReload();
  });
  addEventListener("resize", fitToViewport);
  function full() {
    if (!document.fullscreenElement) { var p = document.documentElement.requestFullscreen && document.documentElement.requestFullscreen(); if (p && p.catch) p.catch(function () {}); }
    else if (document.exitFullscreen) document.exitFullscreen();
  }
  document.addEventListener("dblclick", full);
  document.addEventListener("keydown", function (e) { if (e.key === "f" || e.key === "F") full(); });
}
